import { expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { PNG } from "pngjs";
import { createHash } from "node:crypto";
import { createReadStream } from "node:fs";

// Run only against the explicitly started local integration fixture. It exposes
// an unauthenticated test S3 adapter and must never be deployed.
test("standalone CLI syncs revisions with the real local management Worker and R2", async () => {
  const origin = process.env.CASTLOOP_LOCAL_INTEGRATION_ORIGIN;
  if (origin !== "http://127.0.0.1:18787") throw new Error("Expected the dedicated local integration fixture on 127.0.0.1:18787");
  const base = await mkdtemp(join(tmpdir(), "castloop-real-worker-"));
  const first = join(base, "first"), second = join(base, "second"), collision = join(base, "collision");
  const binary = resolve(import.meta.dir, "../../../dist/castloop");
  const env = { ...Bun.env, XDG_CONFIG_HOME: join(base, "config"), CASTLOOP_ADMIN_TOKEN: "local-integration-token", CASTLOOP_R2_ACCESS_KEY_ID: "local-test", CASTLOOP_R2_SECRET_ACCESS_KEY: "local-test" };
  async function run(root: string, ...args: string[]) {
    const child = Bun.spawn([binary, ...args], { cwd: root, env, stdout: "pipe", stderr: "pipe" });
    const [code, output, error] = await Promise.all([child.exited, new Response(child.stdout).text(), new Response(child.stderr).text()]);
    return { code, output, error };
  }
  async function configured(root: string) {
    await mkdir(root);
    expect((await run(root, "init")).code).toBe(0);
    for (const [key, value] of [["management_url", origin!], ["r2_endpoint", origin!], ["account_id", "a".repeat(32)], ["management_bucket", "test-bucket"], ["delivery_bucket", "test-delivery"]]) {
      const result = await run(root, "config", "set", key!, value!);
      expect(result.code).toBe(0);
    }
  }
  try {
    await configured(first);
    await configured(second);
    const created = await run(first, "show", "new");
    expect(created.code).toBe(0);
    const showId = created.output.match(/s-[0-9abcdefghjkmnpqrstvwxyz]{8}/)?.[0];
    expect(showId).toBeDefined();
    const showPath = join(first, showId!, "show.toml");
    const original = await readFile(showPath, "utf8");
    expect((await fetch(`${origin}/__local-fixture/lose-operation`, { method: "POST" })).status).toBe(200);
    const pushed = await run(first, "push", "--show", showId!, "--json");
    const uncertain = JSON.parse(pushed.output) as { shows: { operation_id: string; acceptance: string; receipt_retained: boolean }[] };
    const uncertainOperationId = uncertain.shows[0]!.operation_id;
    expect({ code: pushed.code, error: pushed.error, body: uncertain }).toMatchObject({ code: 1, error: "", body: { shows: [{ show_id: showId, acceptance: "unknown", receipt_retained: true, operation_id: expect.any(String) }] } });
    const retried = await run(first, "operation", "retry", uncertainOperationId, "--json");
    expect({ code: retried.code, error: retried.error, body: JSON.parse(retried.output) }).toMatchObject({ code: 2, error: "", body: { show_id: showId, result: { acceptance: "already_accepted", accepted_revision: 1, validation_issues: expect.arrayContaining([expect.objectContaining({ path: "show.title" })]) } } });
    await configured(collision);
    await mkdir(join(collision, showId!));
    await writeFile(join(collision, showId!, "show.toml"), original);
    const collided = await run(collision, "push", "--show", showId!, "--json");
    const collisionResult = JSON.parse(collided.output) as { show_id_changes: { old_show_id: string; new_show_id: string }[]; shows: { show_id: string; result: { acceptance: string } }[] };
    expect({ code: collided.code, error: collided.error }).toEqual({ code: 2, error: "" });
    expect(collisionResult.show_id_changes).toHaveLength(1);
    const freshShowId = collisionResult.show_id_changes[0]!.new_show_id;
    expect(freshShowId).not.toBe(showId);
    expect(collisionResult.shows[0]).toMatchObject({ show_id: freshShowId, result: { acceptance: "accepted" } });
    expect(await readFile(join(collision, freshShowId, "show.toml.bak"), "utf8")).toBe(original);
    const originalSnapshot = await fetch(`${origin}/v1/shows/${showId}/snapshot`, { headers: { Authorization: "Bearer local-integration-token" } });
    expect(await originalSnapshot.json()).toMatchObject({ show_id: showId, revision: 1 });
    const listed = await run(first, "show", "list", "--json");
    expect({ code: listed.code, body: JSON.parse(listed.output) }).toMatchObject({ code: 0, body: { shows: expect.arrayContaining([expect.objectContaining({ show_id: showId, revision: 1 })]) } });
    const pulled = await run(second, "pull", "--show", showId!, "--json");
    expect({ code: pulled.code, error: pulled.error, body: JSON.parse(pulled.output) }).toMatchObject({ code: 0, error: "", body: { shows: [{ show_id: showId, revision: 1 }] } });
    expect(await readFile(join(second, showId!, "show.toml"), "utf8")).toBe(original);
    const local = `${original}\n# local edit\n`, remote = `${original}\n# remote edit\n`;
    await writeFile(join(second, showId!, "show.toml"), local);
    await writeFile(showPath, remote);
    const updated = await run(first, "push", "--show", showId!, "--json");
    expect({ code: updated.code, output: JSON.parse(updated.output) }).toMatchObject({ code: 2, output: { shows: [{ result: { accepted_revision: 2 } }] } });
    const stale = await run(second, "push", "--show", showId!, "--json");
    expect({ code: stale.code, output: JSON.parse(stale.output) }).toMatchObject({ code: 3, output: { shows: [{ show_id: showId, acceptance: "rejected" }] } });
    const conflict = await run(second, "pull", "--show", showId!, "--json");
    expect({ code: conflict.code, output: JSON.parse(conflict.output) }).toMatchObject({ code: 0, output: { shows: [{ revision: 2, backups: [join(second, showId!, "show.toml.bak")] }] } });
    expect(await readFile(join(second, showId!, "show.toml"), "utf8")).toBe(remote);
    expect(await readFile(join(second, showId!, "show.toml.bak"), "utf8")).toBe(local);
    const publicResponse = await fetch(`${origin}/public/${showId}/feed.xml`);
    expect(publicResponse.status).toBe(404);
    const publishedShow = `schema_version = 1\nid = "${showId}"\npublish = true\ntitle = "Local Integration Show"\ndescription = "Show description"\nwebsite = "https://example.com"\nlanguage = "en"\ntimezone = "UTC"\nartwork = "cover.png"\ncategories = [{name="Technology"}]\nexplicit = false\n`;
    await writeFile(showPath, publishedShow);
    const enabled = await run(first, "push", "--show", showId!, "--json");
    expect(JSON.parse(enabled.output)).toMatchObject({ shows: [{ result: { acceptance: "accepted", accepted_revision: 3 } }] });
    const image = new PNG({ width: 1400, height: 1400 });
    image.data.fill(255);
    const coverPath = join(base, "cover.png");
    await writeFile(coverPath, PNG.sync.write(image, { colorType: 2 }));
    const cover = await run(first, "show", "upload-cover", showId!, coverPath, "--json");
    expect({ code: cover.code, output: JSON.parse(cover.output), error: cover.error }).toMatchObject({ code: 0, error: "", output: { result: { acceptance: "accepted" } } });
    const madeEpisode = await run(first, "episode", "new", showId!);
    expect(madeEpisode.code).toBe(0);
    const episodeId = madeEpisode.output.match(/e-[0-9abcdefghjkmnpqrstvwxyz]{8}/)?.[0];
    expect(episodeId).toBeDefined();
    const episodePath = join(first, showId!, episodeId!, "episode.toml");
    await writeFile(episodePath, `schema_version = 1\nid = "${episodeId}"\nshow_id = "${showId}"\npublish = true\ntitle = "Local episode"\ndescription = "Episode description"\npublished_at = 2020-01-01T00:00:00Z\n`);
    const episodePush = await run(first, "push", "--show", showId!, "--json");
    expect(JSON.parse(episodePush.output)).toMatchObject({ shows: [{ result: { acceptance: "accepted" } }] });
    const audioPath = resolve(import.meta.dir, "../test/fixture.mp3");
    const audio = await run(first, "episode", "upload-audio", showId!, episodeId!, audioPath, "--json");
    expect({ code: audio.code, error: audio.error, output: JSON.parse(audio.output) }).toMatchObject({ code: 0, error: "", output: { result: { acceptance: "accepted", delivery: "applied" } } });
    if (process.env.CASTLOOP_LOCAL_LARGE_AUDIO === "1") {
      for (const name of ["50mib-silence.mp3", "100mib-silence.mp3"]) {
        const largePath = resolve(import.meta.dir, `../../../.local-test/mp3-decoder/${name}`);
        const uploaded = await run(first, "episode", "upload-audio", showId!, episodeId!, largePath, "--json");
        expect({ code: uploaded.code, error: uploaded.error, output: JSON.parse(uploaded.output) }).toMatchObject({ code: 0, error: "", output: { result: { acceptance: "accepted", delivery: "applied" } } });
        const expected = createHash("sha256"), actual = createHash("sha256");
        for await (const chunk of createReadStream(largePath)) expected.update(chunk);
        const response = await fetch(`${origin}/public/${showId}/${episodeId}/audio.mp3`);
        expect(response.status).toBe(200);
        expect(response.body).not.toBeNull();
        for await (const chunk of response.body!) actual.update(chunk);
        expect(actual.digest("hex")).toBe(expected.digest("hex"));
      }
      const restoredAudio = await run(first, "episode", "upload-audio", showId!, episodeId!, audioPath, "--json");
      expect({ code: restoredAudio.code, error: restoredAudio.error }).toEqual({ code: 0, error: "" });
    }
    const checked = await run(first, "check", "--show", showId!, "--json");
    expect({ code: checked.code, body: JSON.parse(checked.output) }).toMatchObject({ code: 0, body: { checks: [{ show_id: showId, result: { issues: [] } }] } });
    const inventory = await run(first, "inventory", "--show", showId!, "--json");
    expect({ code: inventory.code, body: JSON.parse(inventory.output) }).toMatchObject({ code: 0, body: { shows: [{ show_id: showId, issues: [], records: expect.arrayContaining([expect.objectContaining({ kind: "audio", episode_id: episodeId, state: "present" })]) }] } });
    const preview = await run(first, "cleanup", "--show", showId!, "--older-than", "1", "--json");
    expect({ code: preview.code, body: JSON.parse(preview.output) }).toMatchObject({ code: 0, body: { apply_requested: false, previews: [{ show_id: showId, candidates: [] }] } });
    const feed = await fetch(`${origin}/public/${showId}/feed.xml`);
    expect(feed.status).toBe(200);
    const initialFeed = await feed.text();
    expect(initialFeed).toContain("Local episode");
    const guid = initialFeed.match(/<guid[^>]*>([^<]+)<\/guid>/)?.[1];
    expect(guid).toBeDefined();
    const media = await fetch(`${origin}/public/${showId}/${episodeId}/audio.mp3`);
    expect(media.status).toBe(200);
    expect(Buffer.from(await media.arrayBuffer())).toEqual(await readFile(audioPath));
    const aged = await fetch(`${origin}/__local-fixture/age/${showId}`, { method: "POST" });
    expect(aged.status).toBe(200);
    expect((await aged.json() as { count: number }).count).toBeGreaterThan(3);
    const initialDeletes = await (await fetch(`${origin}/__local-fixture/delete-count`)).json() as { count: number };
    expect((await fetch(`${origin}/__local-fixture/lose-claim`, { method: "POST" })).status).toBe(200);
    const uncertainClaim = await run(first, "cleanup", "--show", showId!, "--older-than", "1", "--apply", "--yes", "--json");
    expect({ code: uncertainClaim.code, error: uncertainClaim.error, body: JSON.parse(uncertainClaim.output) }).toMatchObject({ code: 1, error: "", body: { events: expect.arrayContaining([expect.objectContaining({ type: "claim_prepared", show_id: showId })]) } });
    expect((await (await fetch(`${origin}/__local-fixture/delete-count`)).json() as { count: number }).count).toBe(initialDeletes.count);
    expect((await fetch(`${origin}/__local-fixture/lose-completion`, { method: "POST" })).status).toBe(200);
    // Recover the server-side claim from a different workspace without its receipt.
    const cleanup = await run(second, "cleanup", "--show", showId!, "--older-than", "1", "--apply", "--yes", "--json");
    const cleanupBody = JSON.parse(cleanup.output) as { events: { type: string; key?: string; issues?: string[] }[] };
    expect({ code: cleanup.code, error: cleanup.error }).toEqual({ code: 1, error: "" });
    expect(cleanupBody.events.some(event => event.type === "pending")).toBe(false);
    const beforeRetry = await (await fetch(`${origin}/__local-fixture/delete-count`)).json() as { count: number };
    expect(beforeRetry.count).toBeGreaterThan(0);
    const cleanupRetry = await run(first, "cleanup", "--show", showId!, "--older-than", "1", "--apply", "--yes", "--json");
    expect({ code: cleanupRetry.code, error: cleanupRetry.error, body: JSON.parse(cleanupRetry.output) }).toMatchObject({ code: 0, error: "", body: { events: expect.arrayContaining([expect.objectContaining({ type: "pending", show_id: showId })]) } });
    expect((JSON.parse(cleanupRetry.output) as { events: { type: string; issues?: string[] }[] }).events.some(event => event.type === "skipped" && event.issues?.includes("protected"))).toBe(true);
    const afterRetry = await (await fetch(`${origin}/__local-fixture/delete-count`)).json() as { count: number };
    expect(afterRetry.count).toBe(beforeRetry.count);
    const afterCleanup = await run(first, "check", "--show", showId!, "--json");
    expect({ code: afterCleanup.code, body: JSON.parse(afterCleanup.output) }).toMatchObject({ code: 0, body: { checks: [{ show_id: showId, result: { issues: [] } }] } });
    expect(Buffer.from(await (await fetch(`${origin}/public/${showId}/${episodeId}/audio.mp3`)).arrayBuffer())).toEqual(await readFile(audioPath));
    const episodeBody = await readFile(episodePath, "utf8");
    await writeFile(showPath, publishedShow.replace('title = "Local Integration Show"', 'title = "Invalid\\u0001"'));
    const invalidShow = await run(first, "push", "--show", showId!, "--json");
    expect({ code: invalidShow.code, body: JSON.parse(invalidShow.output) }).toMatchObject({ code: 2, body: { shows: [{ result: { acceptance: "accepted", validation_issues: expect.arrayContaining([expect.objectContaining({ path: "show.title" })]) } }] } });
    expect(await (await fetch(`${origin}/public/${showId}/feed.xml`)).text()).toContain("Local episode");
    expect(Buffer.from(await (await fetch(`${origin}/public/${showId}/${episodeId}/audio.mp3`)).arrayBuffer())).toEqual(await readFile(audioPath));
    await writeFile(episodePath, episodeBody.replace("Local episode", "Update while invalid"));
    const invalidUpdate = await run(first, "push", "--show", showId!, "--json");
    expect({ code: invalidUpdate.code, body: JSON.parse(invalidUpdate.output) }).toMatchObject({ code: 2, body: { shows: [{ acceptance: "rejected" }] } });
    expect(await (await fetch(`${origin}/public/${showId}/feed.xml`)).text()).not.toContain("Update while invalid");
    await writeFile(showPath, publishedShow);
    await writeFile(episodePath, episodeBody);
    const repaired = await run(first, "push", "--show", showId!, "--json");
    expect({ code: repaired.code, body: JSON.parse(repaired.output) }).toMatchObject({ code: 0, body: { shows: [{ result: { acceptance: "accepted" } }] } });
    await writeFile(episodePath, episodeBody.replace('title = "Local episode"', 'title = "Invalid\\u0002"'));
    const invalidEpisode = await run(first, "push", "--show", showId!, "--json");
    expect({ code: invalidEpisode.code, body: JSON.parse(invalidEpisode.output) }).toMatchObject({ code: 2, body: { shows: [{ result: { acceptance: "accepted", validation_issues: expect.arrayContaining([expect.objectContaining({ path: expect.stringContaining("title") })]) } }] } });
    expect((await fetch(`${origin}/public/${showId}/${episodeId}/audio.mp3`)).status).toBe(404);
    expect(await (await fetch(`${origin}/public/${showId}/feed.xml`)).text()).not.toContain(guid!);
    await writeFile(episodePath, episodeBody.replace("Local episode", "Updated episode"));
    const changed = await run(first, "push", "--show", showId!, "--json");
    expect({ code: changed.code, body: JSON.parse(changed.output) }).toMatchObject({ code: 0, body: { shows: [{ result: { acceptance: "accepted", delivery: "applied" } }] } });
    const updatedFeed = await (await fetch(`${origin}/public/${showId}/feed.xml`)).text();
    expect(updatedFeed).toContain("Updated episode");
    expect(updatedFeed).toContain(guid!);
    const replacementPath = join(base, "replacement.mp3");
    const replacement = Buffer.concat([await readFile(audioPath), Buffer.alloc(128)]);
    await writeFile(replacementPath, replacement);
    const replaced = await run(first, "episode", "upload-audio", showId!, episodeId!, replacementPath, "--json");
    expect({ code: replaced.code, body: JSON.parse(replaced.output) }).toMatchObject({ code: 0, body: { result: { acceptance: "accepted", delivery: "applied" } } });
    expect(Buffer.from(await (await fetch(`${origin}/public/${showId}/${episodeId}/audio.mp3`)).arrayBuffer())).toEqual(replacement);
    expect(await (await fetch(`${origin}/public/${showId}/feed.xml`)).text()).toContain(guid!);
    const removed = await run(first, "episode", "delete", showId!, episodeId!, "--yes", "--json");
    expect({ code: removed.code, body: JSON.parse(removed.output) }).toMatchObject({ code: 0, body: { result: { acceptance: "accepted", delivery: "applied" } } });
    expect((await fetch(`${origin}/public/${showId}/${episodeId}/audio.mp3`)).status).toBe(404);
    expect(await (await fetch(`${origin}/public/${showId}/feed.xml`)).text()).not.toContain("Updated episode");
    const scheduledDraft = await run(first, "episode", "new", showId!);
    const scheduledId = scheduledDraft.output.match(/e-[0-9abcdefghjkmnpqrstvwxyz]{8}/)?.[0];
    expect(scheduledId).toBeDefined();
    const release = new Date(Date.now() + 12000).toISOString();
    await writeFile(join(first, showId!, scheduledId!, "episode.toml"), `schema_version = 1\nid = "${scheduledId}"\nshow_id = "${showId}"\npublish = true\ntitle = "Scheduled episode"\ndescription = "Future release"\npublished_at = ${release}\n`);
    const scheduledMeta = await run(first, "push", "--show", showId!, "--json");
    expect(JSON.parse(scheduledMeta.output)).toMatchObject({ shows: [{ result: { acceptance: "accepted" } }] });
    const scheduledAudio = await run(first, "episode", "upload-audio", showId!, scheduledId!, audioPath, "--json");
    expect({ code: scheduledAudio.code, body: JSON.parse(scheduledAudio.output) }).toMatchObject({ code: 0, body: { result: { acceptance: "accepted", delivery: "scheduled" } } });
    expect((await fetch(`${origin}/public/${showId}/${scheduledId}/audio.mp3`)).status).toBe(404);
    expect(await (await fetch(`${origin}/public/${showId}/feed.xml`)).text()).not.toContain("Scheduled episode");
    const deadline = Date.now() + 30000;
    let releasedFeed = "";
    do {
      await Bun.sleep(300);
      releasedFeed = await (await fetch(`${origin}/public/${showId}/feed.xml`)).text();
    } while (!releasedFeed.includes("Scheduled episode") && Date.now() < deadline);
    expect(releasedFeed).toContain("Scheduled episode");
    expect(Buffer.from(await (await fetch(`${origin}/public/${showId}/${scheduledId}/audio.mp3`)).arrayBuffer())).toEqual(await readFile(audioPath));
    const snapshotPath = join(base, "snapshot.json");
    const exported = await run(first, "export", snapshotPath, "--show", showId!, "--json");
    expect({ code: exported.code, body: JSON.parse(exported.output) }).toMatchObject({ code: 0, body: { shows: [showId] } });
    const scheduledPath = join(first, showId!, scheduledId!, "episode.toml");
    await writeFile(scheduledPath, (await readFile(scheduledPath, "utf8")).replace("publish = true", "publish = false"));
    const withdrawn = await run(first, "push", "--show", showId!, "--json");
    expect({ code: withdrawn.code, body: JSON.parse(withdrawn.output) }).toMatchObject({ code: 0, body: { shows: [{ result: { acceptance: "accepted", delivery: "applied" } }] } });
    expect((await fetch(`${origin}/public/${showId}/${scheduledId}/audio.mp3`)).status).toBe(404);
    expect(await (await fetch(`${origin}/public/${showId}/feed.xml`)).text()).not.toContain("Scheduled episode");
    const deleted = await run(first, "show", "delete", showId!, "--yes", "--json");
    expect({ code: deleted.code, body: JSON.parse(deleted.output) }).toMatchObject({ code: 0, body: { result: { acceptance: "accepted", delivery: "applied" } } });
    expect((await fetch(`${origin}/public/${showId}/feed.xml`)).status).toBe(404);
    const restored = await run(first, "restore", snapshotPath, "--replace", "--yes", "--json");
    expect({ code: restored.code, body: JSON.parse(restored.output) }).toMatchObject({ code: 0, body: { shows: [{ show_id: showId, result: { acceptance: "accepted", delivery: "blocked" } }] } });
    expect((await fetch(`${origin}/public/${showId}/feed.xml`)).status).toBe(404);
    const resumed = await run(first, "restore-resume", showId!, "--yes", "--json");
    expect({ code: resumed.code, body: JSON.parse(resumed.output) }).toMatchObject({ code: 0, body: { result: { acceptance: "accepted", delivery: "applied" } } });
    expect(await (await fetch(`${origin}/public/${showId}/feed.xml`)).text()).toContain("Scheduled episode");
    expect(Buffer.from(await (await fetch(`${origin}/public/${showId}/${scheduledId}/audio.mp3`)).arrayBuffer())).toEqual(await readFile(audioPath));
    const afterRestore = await run(first, "pull", "--show", showId!, "--json");
    expect(afterRestore.code).toBe(0);
    await writeFile(showPath, publishedShow.replace("publish = true", "publish = false"));
    const stopUnconfirmed = await run(first, "push", "--show", showId!, "--json");
    expect(stopUnconfirmed.code).toBe(4);
    expect((await fetch(`${origin}/public/${showId}/feed.xml`)).status).toBe(200);
    const stopped = await run(first, "push", "--show", showId!, "--yes", "--json");
    expect({ code: stopped.code, body: JSON.parse(stopped.output) }).toMatchObject({ code: 0, body: { shows: [{ result: { acceptance: "accepted", delivery: "applied" } }] } });
    expect((await fetch(`${origin}/public/${showId}/feed.xml`)).status).toBe(404);
    expect((await fetch(`${origin}/public/${showId}/${scheduledId}/audio.mp3`)).status).toBe(404);

    // An old saved intent cannot overwrite a newer revision from another workspace.
    const newShow = await run(first, "show", "new");
    const otherId = newShow.output.match(/s-[0-9abcdefghjkmnpqrstvwxyz]{8}/)?.[0];
    expect(otherId).toBeDefined();
    expect((await fetch(`${origin}/__local-fixture/lose-operation`, { method: "POST" })).status).toBe(200);
    const lost = await run(first, "push", "--show", otherId!, "--json");
    const lostId = (JSON.parse(lost.output) as { shows: { operation_id: string }[] }).shows[0]!.operation_id;
    expect(lost.code).toBe(1);
    expect((await run(second, "pull", "--show", otherId!, "--json")).code).toBe(0);
    const otherFile = join(second, otherId!, "show.toml");
    const newer = `${await readFile(otherFile, "utf8")}\n# newer accepted revision\n`;
    await writeFile(otherFile, newer);
    const newerPush = await run(second, "push", "--show", otherId!, "--json");
    expect({ code: newerPush.code, body: JSON.parse(newerPush.output) }).toMatchObject({ code: 2, body: { shows: [{ result: { accepted_revision: 2 } }] } });
    const staleRetry = await run(first, "operation", "retry", lostId, "--json");
    expect({ code: staleRetry.code, body: JSON.parse(staleRetry.output) }).toMatchObject({ code: 3, body: { acceptance: "rejected" } });
    const latest = await run(first, "pull", "--show", otherId!, "--json");
    expect({ code: latest.code, body: JSON.parse(latest.output) }).toMatchObject({ code: 0, body: { shows: [{ revision: 2 }] } });
    expect(await readFile(join(first, otherId!, "show.toml"), "utf8")).toBe(newer);
  } finally { await rm(base, { recursive: true, force: true }); }
}, 60000);
